-- Server-side idempotency for actions that create money records (payments, refunds, sales, invoices, expenses,
-- payroll payments, memberships and renewals). The client sends an Idempotency-Key header; the first request with
-- a key stores its response here in the same transaction as the action, so a retry, a double submit or a
-- concurrent duplicate gets the stored response instead of creating a second record. Keys are kept for a week.
CREATE TABLE idempotency_keys (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id    bigint        NOT NULL REFERENCES businesses (id),
    user_id        bigint        NOT NULL REFERENCES users (id),
    idem_key       varchar(100)  NOT NULL,
    operation      varchar(100)  NOT NULL,
    request_hash   varchar(64)   NOT NULL,
    response_body  text,
    created_at     timestamptz   NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_idempotency_keys ON idempotency_keys (business_id, user_id, idem_key);
CREATE INDEX ix_idempotency_keys_created ON idempotency_keys (created_at);
