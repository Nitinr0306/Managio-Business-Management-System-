CREATE TABLE invoices (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id         bigint         NOT NULL REFERENCES businesses (id) ON DELETE CASCADE,
    number              int            NOT NULL,
    customer_id         bigint         REFERENCES customers (id),
    membership_id       bigint         REFERENCES memberships (id),
    issued_on           date           NOT NULL,
    due_on              date           NOT NULL,
    subtotal            numeric(12, 2) NOT NULL,
    discount            numeric(12, 2) NOT NULL DEFAULT 0,
    tax                 numeric(12, 2) NOT NULL DEFAULT 0,
    total               numeric(12, 2) NOT NULL,
    notes               varchar(500),
    status              varchar(10)    NOT NULL DEFAULT 'ISSUED',
    voided_at           timestamptz,
    void_reason         varchar(300),
    created_by_user_id  bigint         REFERENCES users (id),
    created_at          timestamptz    NOT NULL DEFAULT now(),
    updated_at          timestamptz    NOT NULL DEFAULT now(),
    version             bigint         NOT NULL DEFAULT 0,
    CONSTRAINT ck_invoices_status CHECK (status IN ('ISSUED', 'VOID')),
    CONSTRAINT ck_invoices_amounts CHECK (subtotal >= 0 AND discount >= 0 AND tax >= 0 AND total >= 0 AND discount <= subtotal)
);
CREATE UNIQUE INDEX ux_invoices_business_number ON invoices (business_id, number);
CREATE INDEX ix_invoices_business_due ON invoices (business_id, due_on) WHERE status = 'ISSUED';
CREATE INDEX ix_invoices_customer ON invoices (customer_id);
CREATE INDEX ix_invoices_membership ON invoices (membership_id);

CREATE TABLE invoice_lines (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id   bigint         NOT NULL REFERENCES invoices (id) ON DELETE CASCADE,
    offering_id  bigint         REFERENCES offerings (id),
    description  varchar(200)   NOT NULL,
    quantity     numeric(10, 2) NOT NULL,
    unit_price   numeric(12, 2) NOT NULL,
    tax_rate     numeric(5, 2)  NOT NULL DEFAULT 0,
    amount       numeric(12, 2) NOT NULL,
    position     int            NOT NULL,
    CONSTRAINT ck_invoice_lines_quantity CHECK (quantity > 0)
);
CREATE INDEX ix_invoice_lines_invoice ON invoice_lines (invoice_id);

CREATE TABLE payments (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id          bigint         NOT NULL REFERENCES businesses (id) ON DELETE CASCADE,
    number               int            NOT NULL,
    kind                 varchar(10)    NOT NULL DEFAULT 'PAYMENT',
    customer_id          bigint         REFERENCES customers (id),
    invoice_id           bigint         NOT NULL REFERENCES invoices (id),
    refund_of_id         bigint         REFERENCES payments (id),
    amount               numeric(12, 2) NOT NULL,
    method               varchar(20)    NOT NULL,
    reference            varchar(100),
    paid_on              date           NOT NULL,
    received_at          timestamptz    NOT NULL DEFAULT now(),
    received_by_user_id  bigint         REFERENCES users (id),
    notes                varchar(500),
    voided_at            timestamptz,
    void_reason          varchar(300),
    created_at           timestamptz    NOT NULL DEFAULT now(),
    version              bigint         NOT NULL DEFAULT 0,
    CONSTRAINT ck_payments_kind CHECK (kind IN ('PAYMENT', 'REFUND')),
    CONSTRAINT ck_payments_amount CHECK (amount > 0),
    CONSTRAINT ck_payments_method CHECK (method IN ('CASH', 'UPI', 'CARD', 'BANK_TRANSFER', 'CHEQUE', 'ONLINE', 'OTHER')),
    CONSTRAINT ck_payments_refund_link CHECK ((kind = 'REFUND') = (refund_of_id IS NOT NULL))
);
CREATE UNIQUE INDEX ux_payments_business_number ON payments (business_id, number);
CREATE INDEX ix_payments_business_paid_on ON payments (business_id, paid_on);
CREATE INDEX ix_payments_invoice ON payments (invoice_id);
CREATE INDEX ix_payments_customer ON payments (customer_id);

-- =====================================================================================
-- Expenses and payroll
-- =====================================================================================

CREATE TABLE expense_categories (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id  bigint        NOT NULL REFERENCES businesses (id) ON DELETE CASCADE,
    name         varchar(60)   NOT NULL,
    system_key   varchar(30),
    archived     boolean       NOT NULL DEFAULT false,
    created_at   timestamptz   NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_expense_categories_name ON expense_categories (business_id, lower(name));

CREATE TABLE payroll_entries (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id     bigint         NOT NULL REFERENCES businesses (id) ON DELETE CASCADE,
    team_member_id  bigint         NOT NULL REFERENCES team_members (id) ON DELETE CASCADE,
    period          date           NOT NULL,
    amount          numeric(12, 2) NOT NULL,
    notes           varchar(300),
    created_at      timestamptz    NOT NULL DEFAULT now(),
    version         bigint         NOT NULL DEFAULT 0,
    CONSTRAINT ck_payroll_period CHECK (extract(day FROM period) = 1),
    CONSTRAINT ck_payroll_amount CHECK (amount >= 0)
);
CREATE UNIQUE INDEX ux_payroll_member_period ON payroll_entries (team_member_id, period);
CREATE INDEX ix_payroll_business_period ON payroll_entries (business_id, period);

CREATE TABLE expenses (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id          bigint         NOT NULL REFERENCES businesses (id) ON DELETE CASCADE,
    category_id          bigint         NOT NULL REFERENCES expense_categories (id),
    amount               numeric(12, 2) NOT NULL,
    spent_on             date           NOT NULL,
    method               varchar(20)    NOT NULL,
    payee                varchar(150),
    description          varchar(500),
    reference            varchar(100),
    payroll_entry_id     bigint         REFERENCES payroll_entries (id),
    request_id           bigint,
    recorded_by_user_id  bigint         REFERENCES users (id),
    voided_at            timestamptz,
    void_reason          varchar(300),
    created_at           timestamptz    NOT NULL DEFAULT now(),
    updated_at           timestamptz    NOT NULL DEFAULT now(),
    version              bigint         NOT NULL DEFAULT 0,
    CONSTRAINT ck_expenses_amount CHECK (amount > 0),
    CONSTRAINT ck_expenses_method CHECK (method IN ('CASH', 'UPI', 'CARD', 'BANK_TRANSFER', 'CHEQUE', 'ONLINE', 'OTHER'))
);
CREATE INDEX ix_expenses_business_spent ON expenses (business_id, spent_on);
CREATE INDEX ix_expenses_payroll ON expenses (payroll_entry_id);

-- =====================================================================================
-- Operations: tasks, requests, day book, notifications, activity
-- =====================================================================================

CREATE TABLE tasks (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id         bigint        NOT NULL REFERENCES businesses (id) ON DELETE CASCADE,
    title               varchar(180)  NOT NULL,
    description         text,
    status              varchar(20)   NOT NULL DEFAULT 'OPEN',
    priority            varchar(10)   NOT NULL DEFAULT 'NORMAL',
    due_on              date,
    repeat              varchar(10)   NOT NULL DEFAULT 'NONE',
    assignee_id         bigint        REFERENCES team_members (id) ON DELETE SET NULL,
    customer_id         bigint        REFERENCES customers (id) ON DELETE SET NULL,
    created_by_user_id  bigint        REFERENCES users (id),
    completed_at        timestamptz,
    created_at          timestamptz   NOT NULL DEFAULT now(),
    updated_at          timestamptz   NOT NULL DEFAULT now(),
    version             bigint        NOT NULL DEFAULT 0,
    CONSTRAINT ck_tasks_status CHECK (status IN ('OPEN', 'IN_PROGRESS', 'DONE', 'CANCELLED')),
    CONSTRAINT ck_tasks_priority CHECK (priority IN ('LOW', 'NORMAL', 'HIGH', 'URGENT')),
    CONSTRAINT ck_tasks_repeat CHECK (repeat IN ('NONE', 'DAILY', 'WEEKLY', 'MONTHLY'))
);
CREATE INDEX ix_tasks_business_status ON tasks (business_id, status, due_on);
CREATE INDEX ix_tasks_assignee ON tasks (assignee_id, status);

CREATE TABLE requests (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id             bigint         NOT NULL REFERENCES businesses (id) ON DELETE CASCADE,
    type                    varchar(20)    NOT NULL,
    title                   varchar(180)   NOT NULL,
    details                 text,
    amount                  numeric(12, 2),
    expense_category_id     bigint         REFERENCES expense_categories (id),
    starts_on               date,
    ends_on                 date,
    invoice_id              bigint         REFERENCES invoices (id),
    status                  varchar(20)    NOT NULL DEFAULT 'PENDING',
    requested_by_member_id  bigint         NOT NULL REFERENCES team_members (id),
    decided_by_user_id      bigint         REFERENCES users (id),
    decided_at              timestamptz,
    decision_note           varchar(500),
    created_at              timestamptz    NOT NULL DEFAULT now(),
    updated_at              timestamptz    NOT NULL DEFAULT now(),
    version                 bigint         NOT NULL DEFAULT 0,
    CONSTRAINT ck_requests_type CHECK (type IN ('EXPENSE', 'PURCHASE', 'LEAVE', 'DISCOUNT', 'OTHER')),
    CONSTRAINT ck_requests_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED')),
    CONSTRAINT ck_requests_amount CHECK (amount IS NULL OR amount > 0),
    CONSTRAINT ck_requests_dates CHECK (ends_on IS NULL OR starts_on IS NULL OR ends_on >= starts_on)
);
CREATE INDEX ix_requests_business_status ON requests (business_id, status, created_at DESC);
CREATE INDEX ix_requests_requester ON requests (requested_by_member_id, created_at DESC);

ALTER TABLE expenses ADD CONSTRAINT fk_expenses_request FOREIGN KEY (request_id) REFERENCES requests (id);

CREATE TABLE day_closes (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id        bigint         NOT NULL REFERENCES businesses (id) ON DELETE CASCADE,
    business_date      date           NOT NULL,
    opening_cash       numeric(12, 2) NOT NULL,
    cash_in            numeric(12, 2) NOT NULL,
    cash_out           numeric(12, 2) NOT NULL,
    expected_cash      numeric(12, 2) NOT NULL,
    counted_cash       numeric(12, 2) NOT NULL,
    difference         numeric(12, 2) NOT NULL,
    notes              varchar(500),
    closed_by_user_id  bigint         REFERENCES users (id),
    closed_at          timestamptz    NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_day_closes_business_date ON day_closes (business_id, business_date);

CREATE TABLE notifications (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      bigint        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    business_id  bigint        REFERENCES businesses (id) ON DELETE CASCADE,
    kind         varchar(40)   NOT NULL,
    title        varchar(200)  NOT NULL,
    body         varchar(500),
    link         varchar(300),
    read_at      timestamptz,
    created_at   timestamptz   NOT NULL DEFAULT now()
);
CREATE INDEX ix_notifications_user ON notifications (user_id, created_at DESC);

CREATE TABLE activity_events (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id  bigint        NOT NULL REFERENCES businesses (id) ON DELETE CASCADE,
    actor_type   varchar(10)   NOT NULL,
    actor_id     bigint,
    actor_name   varchar(150),
    action       varchar(60)   NOT NULL,
    entity_type  varchar(30),
    entity_id    bigint,
    summary      varchar(500)  NOT NULL,
    ip_address   varchar(45),
    created_at   timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT ck_activity_actor_type CHECK (actor_type IN ('USER', 'CUSTOMER', 'SYSTEM'))
