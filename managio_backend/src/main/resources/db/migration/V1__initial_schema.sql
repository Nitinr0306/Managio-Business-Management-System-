CREATE TABLE customers (
    id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id              bigint        NOT NULL REFERENCES businesses (id) ON DELETE CASCADE,
    number                   int           NOT NULL,
    full_name                varchar(150)  NOT NULL,
    phone                    varchar(20),
    email                    varchar(255),
    date_of_birth            date,
    gender                   varchar(10),
    address                  varchar(300),
    guardian_name            varchar(150),
    guardian_phone           varchar(20),
    notes                    text,
    status                   varchar(20)   NOT NULL DEFAULT 'ACTIVE',
    joined_on                date          NOT NULL,
    portal_enabled           boolean       NOT NULL DEFAULT false,
    portal_password_hash     varchar(100),
    portal_email_verified_at timestamptz,
    failed_sign_in_count     int           NOT NULL DEFAULT 0,
    locked_until             timestamptz,
    last_sign_in_at          timestamptz,
    created_by_user_id       bigint        REFERENCES users (id),
    created_at               timestamptz   NOT NULL DEFAULT now(),
    updated_at               timestamptz   NOT NULL DEFAULT now(),
    version                  bigint        NOT NULL DEFAULT 0,
    CONSTRAINT ck_customers_status CHECK (status IN ('ACTIVE', 'ARCHIVED'))
);
CREATE UNIQUE INDEX ux_customers_business_number ON customers (business_id, number);
CREATE UNIQUE INDEX ux_customers_portal_email ON customers (business_id, lower(email)) WHERE portal_enabled AND email IS NOT NULL;
CREATE UNIQUE INDEX ux_customers_portal_phone ON customers (business_id, phone) WHERE portal_enabled AND phone IS NOT NULL;
CREATE INDEX ix_customers_business_name ON customers (business_id, lower(full_name));
CREATE INDEX ix_customers_business_phone ON customers (business_id, phone);
CREATE INDEX ix_customers_business_created ON customers (business_id, created_at DESC);

CREATE TABLE customer_groups (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id  bigint        NOT NULL REFERENCES businesses (id) ON DELETE CASCADE,
    name         varchar(80)   NOT NULL,
    description  varchar(300),
    created_at   timestamptz   NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_customer_groups_name ON customer_groups (business_id, lower(name));

CREATE TABLE customer_group_members (
    group_id     bigint NOT NULL REFERENCES customer_groups (id) ON DELETE CASCADE,
    customer_id  bigint NOT NULL REFERENCES customers (id) ON DELETE CASCADE,
    PRIMARY KEY (group_id, customer_id)
);
CREATE INDEX ix_customer_group_members_customer ON customer_group_members (customer_id);

CREATE TABLE attendance (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id        bigint       NOT NULL REFERENCES businesses (id) ON DELETE CASCADE,
    customer_id        bigint       NOT NULL REFERENCES customers (id) ON DELETE CASCADE,
    attended_on        date         NOT NULL,
    checked_in_at      timestamptz  NOT NULL DEFAULT now(),
    marked_by_user_id  bigint       REFERENCES users (id)
);
CREATE UNIQUE INDEX ux_attendance_customer_day ON attendance (customer_id, attended_on);
CREATE INDEX ix_attendance_business_day ON attendance (business_id, attended_on);

-- =====================================================================================
-- Offerings and memberships
-- =====================================================================================

CREATE TABLE offerings (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id     bigint         NOT NULL REFERENCES businesses (id) ON DELETE CASCADE,
    kind            varchar(10)    NOT NULL,
    name            varchar(120)   NOT NULL,
    description     varchar(500),
    price           numeric(12, 2) NOT NULL,
    tax_rate        numeric(5, 2)  NOT NULL DEFAULT 0,
    duration_value  int,
    duration_unit   varchar(10),
    installments    int            NOT NULL DEFAULT 1,
    sku             varchar(40),
    track_stock     boolean        NOT NULL DEFAULT false,
    stock_quantity  int,
    active          boolean        NOT NULL DEFAULT true,
    created_at      timestamptz    NOT NULL DEFAULT now(),
    updated_at      timestamptz    NOT NULL DEFAULT now(),
    version         bigint         NOT NULL DEFAULT 0,
    CONSTRAINT ck_offerings_kind CHECK (kind IN ('PLAN', 'SERVICE', 'PRODUCT')),
    CONSTRAINT ck_offerings_price CHECK (price >= 0),
    CONSTRAINT ck_offerings_tax CHECK (tax_rate >= 0 AND tax_rate <= 100),
    CONSTRAINT ck_offerings_installments CHECK (installments BETWEEN 1 AND 24),
    CONSTRAINT ck_offerings_plan_duration CHECK (
        kind <> 'PLAN' OR (duration_value > 0 AND duration_unit IN ('DAYS', 'MONTHS')))
);
CREATE INDEX ix_offerings_business_kind ON offerings (business_id, kind, active);

CREATE TABLE memberships (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id         bigint         NOT NULL REFERENCES businesses (id) ON DELETE CASCADE,
    customer_id         bigint         NOT NULL REFERENCES customers (id),
    offering_id         bigint         NOT NULL REFERENCES offerings (id),
    starts_on           date           NOT NULL,
    ends_on             date           NOT NULL,
    price               numeric(12, 2) NOT NULL,
    status              varchar(20)    NOT NULL DEFAULT 'ACTIVE',
    cancelled_at        timestamptz,
    cancel_reason       varchar(300),
    renewed_from_id     bigint         REFERENCES memberships (id),
    reminder_sent_at    timestamptz,
    created_by_user_id  bigint         REFERENCES users (id),
    created_at          timestamptz    NOT NULL DEFAULT now(),
    updated_at          timestamptz    NOT NULL DEFAULT now(),
    version             bigint         NOT NULL DEFAULT 0,
    CONSTRAINT ck_memberships_status CHECK (status IN ('ACTIVE', 'CANCELLED')),
    CONSTRAINT ck_memberships_dates CHECK (ends_on >= starts_on)
);
CREATE INDEX ix_memberships_business_ends ON memberships (business_id, ends_on) WHERE status = 'ACTIVE';
CREATE INDEX ix_memberships_customer ON memberships (customer_id, ends_on DESC);

-- =====================================================================================
-- Billing
