-- =====================================================================================
-- Identity
-- =====================================================================================

CREATE TABLE users (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                 varchar(255) NOT NULL,
    password_hash         varchar(100),
    full_name             varchar(150) NOT NULL,
    phone                 varchar(20),
    email_verified_at     timestamptz,
    google_subject        varchar(64),
    status                varchar(20)  NOT NULL DEFAULT 'ACTIVE',
    failed_sign_in_count  int          NOT NULL DEFAULT 0,
    locked_until          timestamptz,
    last_sign_in_at       timestamptz,
    created_at            timestamptz  NOT NULL DEFAULT now(),
    updated_at            timestamptz  NOT NULL DEFAULT now(),
    version               bigint       NOT NULL DEFAULT 0,
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'DISABLED'))
);
CREATE UNIQUE INDEX ux_users_email ON users (lower(email));
CREATE UNIQUE INDEX ux_users_google_subject ON users (google_subject) WHERE google_subject IS NOT NULL;

CREATE TABLE refresh_tokens (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_type  varchar(10)  NOT NULL,
    subject_id    bigint       NOT NULL,
    token_hash    varchar(64)  NOT NULL,
    family_id     uuid         NOT NULL,
    expires_at    timestamptz  NOT NULL,
    rotated_at    timestamptz,
    revoked_at    timestamptz,
    user_agent    varchar(255),
    ip_address    varchar(45),
    created_at    timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_refresh_subject_type CHECK (subject_type IN ('USER', 'CUSTOMER'))
);
CREATE UNIQUE INDEX ux_refresh_tokens_hash ON refresh_tokens (token_hash);
CREATE INDEX ix_refresh_tokens_subject ON refresh_tokens (subject_type, subject_id);
CREATE INDEX ix_refresh_tokens_family ON refresh_tokens (family_id);
CREATE INDEX ix_refresh_tokens_expires ON refresh_tokens (expires_at);

CREATE TABLE one_time_tokens (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purpose       varchar(30)  NOT NULL,
    subject_type  varchar(10)  NOT NULL,
    subject_id    bigint       NOT NULL,
    token_hash    varchar(64)  NOT NULL,
    expires_at    timestamptz  NOT NULL,
    used_at       timestamptz,
    created_at    timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_one_time_tokens_purpose CHECK (purpose IN ('EMAIL_VERIFICATION', 'PASSWORD_RESET', 'PORTAL_INVITATION')),
    CONSTRAINT ck_one_time_tokens_subject_type CHECK (subject_type IN ('USER', 'CUSTOMER'))
);
CREATE UNIQUE INDEX ux_one_time_tokens_hash ON one_time_tokens (token_hash);
CREATE INDEX ix_one_time_tokens_subject ON one_time_tokens (subject_type, subject_id, purpose);

CREATE TABLE sign_in_events (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_type  varchar(10)  NOT NULL,
    subject_id    bigint,
    identifier    varchar(255),
    outcome       varchar(20)  NOT NULL,
    detail        varchar(255),
    ip_address    varchar(45),
    user_agent    varchar(255),
    created_at    timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX ix_sign_in_events_subject ON sign_in_events (subject_type, subject_id, created_at DESC);
CREATE INDEX ix_sign_in_events_created ON sign_in_events (created_at);

-- =====================================================================================
-- Businesses, roles and team
-- =====================================================================================

CREATE TABLE businesses (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                   varchar(8)    NOT NULL,
    name                   varchar(150)  NOT NULL,
    type                   varchar(20)   NOT NULL,
    phone                  varchar(20),
    email                  varchar(255),
    address_line           varchar(300),
    city                   varchar(100),
    state                  varchar(100),
    postal_code            varchar(12),
    country                varchar(60)   NOT NULL DEFAULT 'India',
    gstin                  varchar(15),
    timezone               varchar(40)   NOT NULL DEFAULT 'Asia/Kolkata',
    currency               varchar(3)    NOT NULL DEFAULT 'INR',
    modules                text[]        NOT NULL DEFAULT '{}',
    invoice_prefix         varchar(10)   NOT NULL DEFAULT 'INV',
    receipt_prefix         varchar(10)   NOT NULL DEFAULT 'RCT',
    allow_customer_signup  boolean       NOT NULL DEFAULT false,
    renewal_reminders      boolean       NOT NULL DEFAULT true,
    created_by_user_id     bigint        REFERENCES users (id),
    archived_at            timestamptz,
    created_at             timestamptz   NOT NULL DEFAULT now(),
    updated_at             timestamptz   NOT NULL DEFAULT now(),
    version                bigint        NOT NULL DEFAULT 0,
    CONSTRAINT ck_businesses_type CHECK (type IN ('FITNESS', 'SALON', 'COACHING', 'SCHOOL', 'CLINIC', 'RETAIL', 'OTHER')),
    CONSTRAINT ck_businesses_code CHECK (code ~ '^[0-9]{4}[A-Z]{4}$')
);
CREATE UNIQUE INDEX ux_businesses_code ON businesses (code);

CREATE TABLE business_sequences (
    business_id  bigint      NOT NULL REFERENCES businesses (id) ON DELETE CASCADE,
    name         varchar(20) NOT NULL,
    next_value   bigint      NOT NULL DEFAULT 1,
    PRIMARY KEY (business_id, name)
);

CREATE TABLE roles (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id  bigint        NOT NULL REFERENCES businesses (id) ON DELETE CASCADE,
    name         varchar(60)   NOT NULL,
    description  varchar(200),
    permissions  text[]        NOT NULL DEFAULT '{}',
    system_key   varchar(30),
    created_at   timestamptz   NOT NULL DEFAULT now(),
    updated_at   timestamptz   NOT NULL DEFAULT now(),
    version      bigint        NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX ux_roles_business_name ON roles (business_id, lower(name));
CREATE UNIQUE INDEX ux_roles_business_system_key ON roles (business_id, system_key) WHERE system_key IS NOT NULL;

CREATE TABLE team_members (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id     bigint         NOT NULL REFERENCES businesses (id) ON DELETE CASCADE,
    user_id         bigint         NOT NULL REFERENCES users (id),
    role_id         bigint         NOT NULL REFERENCES roles (id),
    status          varchar(20)    NOT NULL DEFAULT 'ACTIVE',
    title           varchar(100),
    employee_code   varchar(20),
    phone           varchar(20),
    joined_on       date           NOT NULL,
    left_on         date,
    monthly_salary  numeric(12, 2),
    notes           text,
    created_at      timestamptz    NOT NULL DEFAULT now(),
    updated_at      timestamptz    NOT NULL DEFAULT now(),
    version         bigint         NOT NULL DEFAULT 0,
    CONSTRAINT ck_team_members_status CHECK (status IN ('ACTIVE', 'SUSPENDED', 'LEFT')),
    CONSTRAINT ck_team_members_salary CHECK (monthly_salary IS NULL OR monthly_salary >= 0)
);
CREATE UNIQUE INDEX ux_team_members_business_user ON team_members (business_id, user_id);
CREATE INDEX ix_team_members_user ON team_members (user_id);

CREATE TABLE invitations (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id          bigint        NOT NULL REFERENCES businesses (id) ON DELETE CASCADE,
    email                varchar(255)  NOT NULL,
    role_id              bigint        NOT NULL REFERENCES roles (id),
    title                varchar(100),
    token_hash           varchar(64)   NOT NULL,
    invited_by_user_id   bigint        REFERENCES users (id),
    expires_at           timestamptz   NOT NULL,
    accepted_at          timestamptz,
    accepted_by_user_id  bigint        REFERENCES users (id),
    revoked_at           timestamptz,
    created_at           timestamptz   NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_invitations_token ON invitations (token_hash);
CREATE INDEX ix_invitations_business ON invitations (business_id, created_at DESC);

-- =====================================================================================
-- Customers
